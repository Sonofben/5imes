// Turns supabase/seed/blog/*.md into a migration that inserts the launch blog posts.
// Posts that already exist (same link) are left alone, so editors' changes are never overwritten.
// Usage: node scripts/build-blog-seed.mjs > supabase/migrations/0027_seed_blog_posts.sql
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/seed/blog";
const q = (s) => { const tag = "$p$"; if (s.includes(tag)) throw new Error("text contains $p$"); return `${tag}${s}${tag}`; };
const unquote = (v) => v.trim().replace(/^"(.*)"$/, "$1");

function parse(src) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error("missing front matter");
  const meta = {}; const faq = []; let inFaq = false; let cur = null;
  for (const line of m[1].split("\n")) {
    if (/^faq:\s*$/.test(line)) { inFaq = true; continue; }
    if (inFaq && /^\s+- q:/.test(line)) { cur = { q: unquote(line.replace(/^\s+- q:/, "")), a: "" }; faq.push(cur); continue; }
    if (inFaq && /^\s+a:/.test(line)) { cur.a = unquote(line.replace(/^\s+a:/, "")); continue; }
    const kv = line.match(/^([a-z_]+):\s*(.*)$/);
    if (kv) { inFaq = false; meta[kv[1]] = unquote(kv[2]); }
  }
  return { meta, faq, body: m[2].trim() + "\n" };
}

const rows = readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => {
  const { meta, faq, body } = parse(readFileSync(join(dir, f), "utf8"));
  for (const k of ["slug", "title", "category", "excerpt", "published"]) if (!meta[k]) throw new Error(`${f}: missing ${k}`);
  const tags = (meta.tags ?? "").split(",").map((t) => t.trim()).filter(Boolean);
  return `  (${q(meta.slug)}, ${q(meta.title)}, ${q(meta.excerpt)}, ${q(body)}, ${q(meta.category)},
   array[${tags.map(q).join(", ")}]::text[], ${meta.seo_title ? q(meta.seo_title) : "null"}, ${meta.seo_description ? q(meta.seo_description) : "null"},
   ${q(JSON.stringify(faq))}::jsonb, 'published', ${q(meta.published + "T08:00:00+01:00")}::timestamptz)`;
});

process.stdout.write(`-- 5ime: launch blog posts (generated by scripts/build-blog-seed.mjs from supabase/seed/blog).
-- Existing posts with the same link are not touched. Apply after 0026.
begin;
insert into public.blog_posts (slug, title, excerpt, body, category, tags, seo_title, seo_description, faq, status, published_at)
values
${rows.join(",\n")}
on conflict (slug) do nothing;
commit;
`);
